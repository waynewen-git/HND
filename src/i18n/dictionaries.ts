export const dictionaries: Record<Locale, Messages> = { en, zh };

export type MessageKey = {
  [K in keyof Messages]: {
    [P in keyof Messages[K] & string]: `${K & string}.${P}`;
  }[keyof Messages[K] & string];
}[keyof Messages];

export function getMessage(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const [ns, id] = key.split(".") as [keyof Messages, string];
  const table = dictionaries[locale][ns] as Record<string, string>;
  let text = table[id] ?? dictionaries.en[ns][id as never] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
